/** Plan report HTML for print / PDF / patient view. */
import { doseShort, exName } from "./exerciseText.js";
import { esc } from "./ui.js";

const KIND = { adjust: "Adjust", keep: "Keep", add: "Add" };

export function buildReportDocument(report) {
  const sl = report.since || {};
  const when = report.createdAt
    ? new Date(report.createdAt).toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" })
    : "";
  const suggHtml = (report.suggestions || []).map((s) => {
    const to = s.to || {};
    const from = s.from;
    const dec = s.decision?.state;
    const status = dec === "ok" ? (s.decision?.edits ? "Accepted with edits" : "Accepted")
      : dec === "no" ? "Dismissed" : "Pending review";
    const title = s.kind === "add" && s.warmup ? `Warm-up · ${exName(s.ex)}` : exName(s.ex);
    return `<section class="rep-sugg">
      <header><span class="rep-tag">${esc(KIND[s.kind] || s.kind)}</span>
        <h2>${esc(title)}</h2><span class="rep-status">${esc(status)}</span></header>
      <p class="rep-dose"><span>${esc(from ? doseShort(from) : "Not in plan")}</span>
        → <strong>${esc(doseShort(to))}</strong></p>
      ${(s.why || []).length ? `<ul>${s.why.map((w) => `<li>${esc(w)}</li>`).join("")}</ul>` : ""}
    </section>`;
  }).join("");

  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/>
<title>Plan report · ${esc(report.patientName || "Patient")}</title>
<style>
  :root { color-scheme: light; }
  body { font-family: Georgia, "Times New Roman", serif; color: #14201a; margin: 0; padding: 32px; line-height: 1.5; background: #fff; }
  h1 { font-size: 1.6rem; margin: 0 0 4px; }
  h2 { font-size: 1.1rem; margin: 0; }
  .muted { color: #55615a; font-size: .9rem; }
  .brand { font-weight: 700; color: #166534; letter-spacing: .02em; margin-bottom: 20px; }
  .stats { display: grid; grid-template-columns: repeat(4, 1fr); gap: 10px; margin: 18px 0 24px; }
  .stat { border: 1px solid #d5ddd7; border-radius: 10px; padding: 12px; }
  .stat b { display: block; font-size: 1.25rem; }
  .msg { background: #eef8f1; border: 1px solid #c9e8d2; border-radius: 12px; padding: 14px 16px; margin: 0 0 24px; white-space: pre-wrap; }
  .rep-sugg { border: 1px solid #d5ddd7; border-radius: 12px; padding: 14px 16px; margin: 0 0 12px; page-break-inside: avoid; }
  .rep-sugg header { display: flex; flex-wrap: wrap; align-items: center; gap: 8px; margin-bottom: 8px; }
  .rep-tag { font-size: .75rem; font-weight: 700; background: #e8f5ec; color: #166534; padding: 3px 8px; border-radius: 999px; }
  .rep-status { margin-left: auto; font-size: .8rem; color: #55615a; }
  .rep-dose { margin: 0 0 8px; font-size: .95rem; }
  ul { margin: 0; padding-left: 1.2em; color: #33443a; }
  .foot { margin-top: 28px; font-size: .8rem; color: #55615a; }
  @media print {
    body { padding: 12px; }
    .no-print { display: none !important; }
  }
</style></head><body>
  <div class="brand">Kinetix · Plan report</div>
  <h1>${esc(report.patientName || "Patient")}</h1>
  <p class="muted">Prepared ${esc(when)}${report.ptName ? ` · ${esc(report.ptName)}` : ""}${report.week != null ? ` · Week ${esc(report.week)}` : ""}
  · Wording: ${report.source === "oci" ? "OCI Generative AI" : "local rules"}</p>
  <div class="stats">
    <div class="stat"><span class="muted">Sessions</span><b>${esc(sl.sessions ?? "–")}/${esc(sl.expected ?? "–")}</b></div>
    <div class="stat"><span class="muted">Good form</span><b>${esc(sl.goodPct != null ? `${sl.goodPct}%` : "–")}</b></div>
    <div class="stat"><span class="muted">Pain</span><b>${esc(sl.pain ?? "–")}/10</b></div>
    <div class="stat"><span class="muted">Effort</span><b>${esc((sl.effort || "–").toString().replace(/_/g, " "))}</b></div>
  </div>
  ${report.message ? `<h2 style="margin-bottom:8px">Message to patient</h2><div class="msg">${esc(report.message)}</div>` : ""}
  <h2 style="margin-bottom:10px">Plan suggestions</h2>
  ${suggHtml || "<p class='muted'>No suggestions in this report.</p>"}
  <p class="foot">Generated by Kinetix. Video never leaves the patient’s device. This summary uses session results and check-ins only.</p>
</body></html>`;
}

/** Open a print window (user can choose Save as PDF). */
export function printReport(report) {
  const html = buildReportDocument(report);
  const w = window.open("", "_blank", "noopener,noreferrer,width=900,height=700");
  if (!w) return { ok: false, reason: "popup_blocked" };
  w.document.open();
  w.document.write(html);
  w.document.close();
  // Allow layout then print
  setTimeout(() => {
    try { w.focus(); w.print(); } catch { /* ignore */ }
  }, 250);
  return { ok: true };
}

/** Download a standalone HTML report (open offline / print later). */
export function downloadReport(report) {
  const html = buildReportDocument(report);
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const a = document.createElement("a");
  const safe = String(report.patientName || "patient").replace(/[^\w\-]+/g, "_").slice(0, 40);
  a.href = URL.createObjectURL(blob);
  a.download = `kinetix-plan-report-${safe}-${(report.id || "draft").slice(0, 12)}.html`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1500);
  return { ok: true };
}

/** Snapshot used for print / publish from the live draft object. */
export function snapshotFromDraft(d, { ptId = "", ptName = "" } = {}) {
  return {
    id: `rep-${Date.now().toString(36)}`,
    draftId: d.id,
    patientId: d.patientId,
    ptId: ptId || "",
    patientName: d.patient?.name || d.patient?.first || "Patient",
    ptName: ptName || "",
    createdAt: new Date().toISOString(),
    message: d.message || "",
    source: d.source || "local",
    week: d.profile?.week,
    since: d.since_last_plan || {},
    suggestions: (d.suggestions || []).map((s) => ({
      id: s.id,
      kind: s.kind,
      ex: s.ex,
      warmup: s.warmup,
      progress: s.progress,
      from: s.from,
      to: { ...s.to, ...(d.decisions?.[s.id]?.edits || {}) },
      why: s.why || [],
      decision: d.decisions?.[s.id] || null,
    })),
  };
}
